"""(ใช้ครั้งเดียว) เวลาต่อการฆ่า (ชีตเลเวล คอลัมน์ J) ใช้ความเร็วตีจริงของสายตี (ชีตสายเลี้ยงตัว คอลัมน์ K "ตีทุก (ms)")
เดิมใช้ ตั้งค่า!C18 = 0.7 วินาทีต่อที แต่ระบบค่าพลังใหม่ตีทุก ~1.17 วินาที → เก็บเลเวลจริงช้ากว่าเป้า 400 ชั่วโมง
หลังแก้ EXP มอน (คำนวณจาก EXP ขึ้นเลเวล ÷ จำนวนที่ต้องฆ่าในเวลาเป้าหมาย) จะคิดใหม่ให้ตรงเป้า
หลังรันต้องให้ Excel คำนวณแล้ว Save ก่อน export
"""
from pathlib import Path
from openpyxl import load_workbook

root = Path(__file__).resolve().parent.parent
path = root / "balance" / "siam-legends-balance.xlsx"
wb = load_workbook(path)
lv, st = wb["เลเวล"], wb["ตั้งค่า"]

r = 5
while lv[f"A{r}"].value is not None:
    lv[f"J{r}"] = f"=ตั้งค่า!$C$20*INDEX(สายเลี้ยงตัว!$K$5:$K$104,MIN(A{r},100))/1000+ตั้งค่า!$C$21"
    r += 1
st["E18"] = "ไม่ใช้แล้ว: เวลาต่อการฆ่าใช้ความเร็วตีของสายตีจากชีตสายเลี้ยงตัว (คอลัมน์ ตีทุก ms)"
wb.save(path)
print(f"แก้สูตรเวลาต่อการฆ่า {r - 5} แถวแล้ว — ให้ Excel คำนวณแล้ว Save ก่อน export")
